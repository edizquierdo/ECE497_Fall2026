def plot_fitness(best_fit, avg_fit, worst_fit, problem_name="XOR"):
    """Plot best, average, and worst fitness over generations."""
    plt.figure(figsize=(10, 6))
    gens = np.arange(len(best_fit))
    plt.plot(gens, best_fit,  label="Best Fitness",  color="green", linewidth=2)
    plt.plot(gens, avg_fit,   label="Mean Fitness",  color="blue",  linewidth=2)
    plt.plot(gens, worst_fit, label="Worst Fitness", color="red",   linewidth=1, linestyle="--")
    plt.axhline(y=1.0, color="black", linestyle=":", alpha=0.5, label="Perfect (1.0)")
    plt.xlabel("Generation")
    plt.ylabel("Fitness")
    plt.title(f"Neuroevolution Performance — {problem_name} Controller")
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.ylim(0, 1.05)
    plt.tight_layout()
    plt.show()


def plot_decision_boundary_custom(best_genome, hidden, activation, best_fitness,
                                   inputs, signs, problem_name="Custom", hidden_sizes=None):
    """Plot the 2-D decision boundary of the evolved network with custom data.

    Args:
        best_genome:  Flat weight vector of the best evolved network.
        hidden:       Number of hidden neurons (used only if hidden_sizes is None).
        activation:   Activation function name.
        best_fitness: Final best fitness value.
        inputs:       Input tensor (can be XOR, random, or convex).
        signs:        Sign labels (can be XOR, random, or convex).
        problem_name: Name to display in the title (e.g., "XOR", "Random(8)", "Convex(6)").
        hidden_sizes: Optional list of hidden-layer sizes, overriding `hidden`.
    """
    best_genome_cpu = best_genome.cpu()
    inputs_cpu = inputs.cpu()
    signs_cpu = signs.cpu()

    net = XORNet(hidden=hidden, activation=activation, hidden_sizes=hidden_sizes).to("cpu")
    utils.vector_to_parameters(best_genome_cpu, net.parameters())

    # ── Grid bounds: add 40 % padding around the actual data range ───────────
    pts_np = inputs_cpu.numpy()
    x_min, x_max = pts_np[:, 0].min(), pts_np[:, 0].max()
    y_min, y_max = pts_np[:, 1].min(), pts_np[:, 1].max()
    x_pad = max((x_max - x_min) * 0.4, 0.3)
    y_pad = max((y_max - y_min) * 0.4, 0.3)
    x_lo, x_hi = x_min - x_pad, x_max + x_pad
    y_lo, y_hi = y_min - y_pad, y_max + y_pad

    # ── Evaluate network on a fine grid ──────────────────────────────────────
    x_vals = torch.linspace(x_lo, x_hi, 300)
    y_vals = torch.linspace(y_lo, y_hi, 300)
    X_grid, Y_grid = torch.meshgrid(x_vals, y_vals, indexing="ij")
    points = torch.stack([X_grid.flatten(), Y_grid.flatten()], dim=-1)
    with torch.no_grad():
        output_map = net(points).view(300, 300).detach().numpy()

    fig, ax = plt.subplots(figsize=(7, 6))

    # Determine appropriate contour levels based on activation function
    # tanh outputs in [-1, 1], sigmoid in [0, 1]
    if activation == "sigmoid":
        # For sigmoid, decision boundary is at output=0.5
        levels_fill = [output_map.min(), 0.5, output_map.max()]
        colors = ["lightblue", "salmon"]
    else:
        # For tanh/relu, decision boundary is at output=0
        levels_fill = [output_map.min(), 0, output_map.max()]
        colors = ["lightblue", "salmon"]

    ax.contourf(X_grid.numpy(), Y_grid.numpy(), output_map,
                levels=levels_fill, colors=colors, alpha=0.5)
    ax.contour(X_grid.numpy(), Y_grid.numpy(), output_map,
               levels=[0] if activation != "sigmoid" else [0.5],
               colors=["black"], linewidths=1.5)

    # ── Scatter training points coloured by expected class ───────────────────
    signs_np = signs_cpu.numpy()
    pos_mask = signs_np > 0
    neg_mask = ~pos_mask

    if pos_mask.any():
        ax.scatter(pts_np[pos_mask, 0], pts_np[pos_mask, 1],
                   c="darkred", marker="x", s=200, linewidths=3,
                   label="Positive class", zorder=5)
    if neg_mask.any():
        ax.scatter(pts_np[neg_mask, 0], pts_np[neg_mask, 1],
                   c="darkblue", marker="o", facecolors="none",
                   s=150, linewidths=2.5, label="Negative class", zorder=5)

    # Use the provided problem name for the title
    if "XOR" in problem_name:
        title = f"Evolved Network — Decision Boundary\n"
        title += f"XOR (hidden={hidden}, activation={activation}, fitness={best_fitness:.4f})"
    else:
        title = f"Evolved Network — Decision Boundary\n"
        title += f"{problem_name} | hidden={hidden}, activation={activation}, fitness={best_fitness:.4f}"

    ax.set_xlim(x_lo, x_hi)
    ax.set_ylim(y_lo, y_hi)
    ax.set_xlabel("x₁")
    ax.set_ylabel("x₂")
    ax.set_aspect("equal")
    ax.legend(fontsize=10)
    ax.set_title(title)
    fig.tight_layout()
    plt.show()


def print_truth_table(best_genome, hidden, activation, hidden_sizes=None):
    """Print the XOR truth table produced by the evolved network."""
    best_genome_cpu = best_genome.cpu()
    net = XORNet(hidden=hidden, activation=activation, hidden_sizes=hidden_sizes).to("cpu")
    utils.vector_to_parameters(best_genome_cpu, net.parameters())

    with torch.no_grad():
        output = net(XOR_INPUTS)

    print("\n=== XOR Truth Table (Evolved Network) ===")
    print(f"{'x₁':>4}  {'x₂':>4}  | {'Output':>9}  | {'Expected':>8}  | {'Correct':>7}")
    print("-" * 50)
    for i, inp in enumerate(XOR_INPUTS):
        expected_sign = XOR_SIGNS[i].item()
        out_val = output[i].item()
        correct = (out_val * expected_sign >= 0)
        expected_str = "positive" if expected_sign > 0 else "negative"
        correct_str  = "✓" if correct else "✗"
        print(f"{inp[0].item():.0f}  {inp[1].item():.0f}  | {out_val:>9.4f}  | {expected_str:>8}  | {correct_str:>7}")

    perfect = all(
        (output[i].item() * XOR_SIGNS[i].item() >= 0) for i in range(4)
    )
    print(f"\nPerfect XOR controller: {perfect}")



# ─────────────────────────────────────────────────────────────
#  1.  Neural Network Definition
# ─────────────────────────────────────────────────────────────

class XORNet(nn.Module):
    """A configurable feedforward network: 2 inputs → hidden layer(s) → 1 output.

    Args:
        hidden:       Number of neurons in the single hidden layer (used only
                      when `hidden_sizes` is not given).
        activation:   Non-linearity to apply after each hidden layer.
                      One of 'tanh', 'sigmoid', or 'relu'.
        hidden_sizes: Optional list of hidden-layer sizes, e.g. [4, 4] for
                      two hidden layers of 4 neurons each. When given,
                      overrides `hidden`. Defaults to None, which is
                      equivalent to `hidden_sizes=[hidden]` (today's
                      single-hidden-layer architecture, unchanged). Pass
                      `hidden_sizes=[]` for zero hidden layers — a bare
                      linear classifier (Linear(2,1), no non-linearity) —
                      to directly test Part 1's "why can't hidden=0 solve
                      XOR" question empirically.
    """

    ACTIVATIONS = {
        "tanh":    nn.Tanh,
        "sigmoid": nn.Sigmoid,
        "relu":    nn.ReLU,
    }

    def __init__(self, hidden=3, activation="tanh", hidden_sizes=None):
        super().__init__()
        if activation not in self.ACTIVATIONS:
            raise ValueError(f"Unknown activation '{activation}'. Choose from {list(self.ACTIVATIONS)}")

        # Note: hidden_sizes=[] is intentionally valid (zero hidden layers,
        # i.e. a linear classifier) — only None falls back to [hidden].
        self.hidden_sizes = list(hidden_sizes) if hidden_sizes is not None else [hidden]

        layers = []
        in_dim = 2
        for h in self.hidden_sizes:
            layers.append(nn.Linear(in_dim, h))         # ... → hidden layer
            layers.append(self.ACTIVATIONS[activation]())  # non-linearity
            in_dim = h
        layers.append(nn.Linear(in_dim, 1))              # hidden layer → output neuron
        self.net = nn.Sequential(*layers)

    def forward(self, x):
        return self.net(x)


# ─────────────────────────────────────────────────────────────
#  2.  XOR Task — Inputs and Expected Signs
# ─────────────────────────────────────────────────────────────

XOR_INPUTS = torch.tensor([
    [0.0, 0.0],   # XOR(0,0) = 0  →  expected negative output
    [0.0, 1.0],   # XOR(0,1) = 1  →  expected positive output
    [1.0, 0.0],   # XOR(1,0) = 1  →  expected positive output
    [1.0, 1.0],   # XOR(1,1) = 0  →  expected negative output
], dtype=torch.float32)

XOR_SIGNS = torch.tensor([-1.0, 1.0, 1.0, -1.0])   # sign of correct output

# Alternate boolean tasks over the same 4 corner points (Part 3 "change the
# task" option). All share XOR_INPUTS; only the expected signs differ.
AND_SIGNS  = torch.tensor([-1.0, -1.0, -1.0,  1.0])
OR_SIGNS   = torch.tensor([-1.0,  1.0,  1.0,  1.0])
XNOR_SIGNS = torch.tensor([ 1.0, -1.0, -1.0,  1.0])

TASKS = {
    "xor":  (XOR_INPUTS, XOR_SIGNS),
    "and":  (XOR_INPUTS, AND_SIGNS),
    "or":   (XOR_INPUTS, OR_SIGNS),
    "xnor": (XOR_INPUTS, XNOR_SIGNS),
}


# ─────────────────────────────────────────────────────────────
#  2b. Random Problem Generator (Generalised XOR)
# ─────────────────────────────────────────────────────────────

def generate_random_problem(num_points=4, seed=None):
    """Generate a random binary classification problem similar to XOR.

    Each data point is generated by:
    - Sampling x, y from Uniform[-0.5, 1.5] (same range as XOR inputs)
    - Assigning a random sign (+1 or -1) with equal probability
    - The sign determines the expected output class

    Args:
        num_points: Number of data points to generate (default: 4).
        seed:       Optional random seed for reproducibility.

    Returns:
        A tuple (inputs, signs) where:
        - inputs: Tensor of shape (num_points, 2) with x, y coordinates
        - signs:  Tensor of shape (num_points,) with +1 or -1 for each point

    Example:
        >>> inputs, signs = generate_random_problem(num_points=10, seed=42)
        >>> # Use these in place of XOR_INPUTS / XOR_SIGNS
    """
    if seed is not None:
        torch.manual_seed(seed)
        np.random.seed(seed)

    # Sample x, y from uniform distribution [-0.5, 1.5]
    # This range centers around the same region as XOR inputs [0, 1]
    inputs = torch.rand(num_points, 2) * 2.0 - 0.5

    # Random signs: +1 or -1 with equal probability
    signs = torch.randint(0, 2, (num_points,), dtype=torch.float32) * 2 - 1

    return inputs, signs


# ─────────────────────────────────────────────────────────────
#  2c. Convex Problem Generator (Alternating Labels on a Circle)
# ─────────────────────────────────────────────────────────────

def generate_convex_problem(num_points=4):
    """Generate a convex-position binary classification problem.

    Points are placed on a circle (convex position) with alternating labels
    around the boundary. This generalises the XOR problem: XOR sits at the
    four corners of a square, and the alternating signs (-, +, -, +) make
    it non-linearly separable with a single hyperplane.

    With N points on a circle labeled alternately, you need N/2 hyperplanes
    to separate each arc of consecutive same-label points.

    This function is fully deterministic: it takes no seed because it takes
    no randomness — given the same num_points, it always returns the same
    points (unlike generate_random_problem, which does sample randomly).

    Args:
        num_points: Number of data points to generate (default: 4).

    Returns:
        A tuple (inputs, signs) where:
        - inputs: Tensor of shape (num_points, 2) with x, y coordinates
                  on a circle centered at (0.5, 0.5) with radius ~0.7
        - signs:  Tensor of shape (num_points,) with alternating +1, -1

    Example:
        >>> inputs, signs = generate_convex_problem(num_points=8)
        >>> # Use these in place of XOR_INPUTS / XOR_SIGNS
    """
    # Center the circle at (0.5, 0.5) with radius chosen to fit nicely
    # in the same region as XOR inputs [0, 1] x [0, 1]
    center = torch.tensor([0.5, 0.5])
    radius = 0.7

    # Generate angles evenly spaced around the circle
    # Starting from angle 0 and going counterclockwise
    # Note: PyTorch linspace doesn't have endpoint=False, so we use numpy then convert
    if num_points == 1:
        angles = torch.tensor([0.0])
    else:
        angles_np = np.linspace(0, 2 * np.pi, num_points, endpoint=False)
        angles = torch.from_numpy(angles_np.astype(np.float32))

    # Compute coordinates on the circle
    x_coords = center[0] + radius * torch.cos(angles)
    y_coords = center[1] + radius * torch.sin(angles)

    inputs = torch.stack([x_coords, y_coords], dim=-1)

    # Alternating signs: start with -1, then +1, -1, +1, ...
    # This matches XOR pattern: [-1, +1, +1, -1] for 4 points
    signs = torch.tensor([(-1) ** i for i in range(num_points)], dtype=torch.float32)

    return inputs, signs



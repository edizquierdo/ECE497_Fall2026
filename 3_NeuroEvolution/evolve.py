# ─────────────────────────────────────────────────────────────
#  4.  Neuroevolution Runner
# ─────────────────────────────────────────────────────────────

def run_neuroevolution(hidden=3, popsize=100, gens=200, mut_stdev=0.5,
                       activation="tanh", verbose=False, seed=None,
                       random_points=None, convex_points=None, device="auto",
                       inputs=None, signs=None, tournament_size=3, eta=20,
                       elitism=True, seed_genome_path=None, seed_noise=0.05,
                       hidden_sizes=None, fitness_mode="sign", task="xor",
                       init_bounds=(-1.0, 1.0), use_crossover=True):
    """Evolve a neural network controller for the XOR task or a random/convex problem.

    The genome encodes all weights and biases of XORNet as a flat real-valued
    vector.  A GeneticAlgorithm with SimulatedBinaryCrossOver and
    GaussianMutation is used to maximise the XOR fitness function.

    Args:
        hidden:         Number of hidden neurons in XORNet.
        popsize:        Number of individuals in the population.
        gens:           Number of generations to run.
        mut_stdev:      Standard deviation for Gaussian mutation.
        activation:     Activation function ('tanh', 'sigmoid', 'relu').
        verbose:        If True, print statistics every 20 generations.
        seed:           Random seed for reproducibility (seeds the EA only —
                        see `inputs`/`signs` below for controlling the problem).
        random_points:  If not None and inputs/signs are not provided, use a
                        random problem with this many points instead of XOR.
        convex_points:  If not None and inputs/signs are not provided, use a
                        convex-position problem with this many points on a circle.
        device:         Target device ('auto', 'cpu', 'cuda', 'mps', etc.).
        inputs:         Optional pre-generated input tensor. If provided (together
                        with `signs`), this exact problem instance is used instead
                        of generating a new one — lets callers (e.g. study.py) hold
                        the problem fixed across repeated runs so that variance
                        across runs reflects only the EA's own stochasticity, not
                        a different random problem each time.
        signs:          Optional pre-generated sign labels, paired with `inputs`.
        tournament_size: Tournament size for SBX crossover.
        eta:            Distribution index for SBX crossover.
        elitism:        If True, best individual always survives to next generation.
        seed_genome_path: Path to a genome saved by a previous --output run. If given,
                        seeds the initial population around this genome (one exact
                        copy plus the rest perturbed by `seed_noise`) instead of
                        starting from scratch.
        seed_noise:     Stdev of the Gaussian perturbation applied to seed_genome_path copies.
        hidden_sizes:   Optional list of hidden-layer sizes, e.g. [4, 4] for two hidden
                        layers. Overrides `hidden` when given (default: None, meaning
                        a single hidden layer of size `hidden`).
        fitness_mode:   'sign' (default, today's exact behavior) or 'mse' (smooth
                        alternative fitness). See make_fitness_fn for details.
        task:           Boolean task to solve ('xor', 'and', 'or', 'xnor') when no
                        explicit inputs/signs/random_points/convex_points are given
                        (default: 'xor', today's exact behavior).
        init_bounds:    (low, high) tuple for the EA's initial genome sampling range
                        (default: (-1.0, 1.0), today's exact behavior).
        use_crossover:  If False, run a mutation-only GA (SimulatedBinaryCrossOver
                        removed from the operator list). Default True.

    Returns:
        best_fit        (np.ndarray): Best fitness at each generation.
        avg_fit         (np.ndarray): Average fitness at each generation.
        worst_fit       (np.ndarray): Worst fitness at each generation.
        best_genome     (torch.Tensor): Flat weight vector of the best individual.
        best_fitness    (float): Final best fitness value.
        inputs          (torch.Tensor): The input data used (XOR, random, or convex).
        signs           (torch.Tensor): The sign labels used (XOR, random, or convex).
        convergence_gen (int or None): Generation at which fitness first reached
                        1.0, or None if perfect fitness was never reached.
    """
    if seed is not None:
        torch.manual_seed(seed)
        np.random.seed(seed)

    target_device = resolve_device(device)
    if verbose:
        print(f"Using device: {target_device}")

    # Use a caller-supplied problem instance if given; otherwise generate one.
    if inputs is not None and signs is not None:
        pass
    elif convex_points is not None:
        inputs, signs = generate_convex_problem(num_points=convex_points)
    elif random_points is not None:
        inputs, signs = generate_random_problem(num_points=random_points, seed=seed)
    else:
        if task not in TASKS:
            raise ValueError(f"Unknown task '{task}'. Choose from {list(TASKS)}")
        inputs, signs = TASKS[task]

    fitness_fn = make_fitness_fn(hidden, activation, inputs=inputs, signs=signs,
                                  device=target_device, hidden_sizes=hidden_sizes,
                                  fitness_mode=fitness_mode)

    # Compute genome length analytically — no need to instantiate a network
    # just to count its parameters (see genome_size() above).
    n_genes = genome_size(hidden=hidden, hidden_sizes=hidden_sizes)

    problem = Problem(
        objective_sense="max",          # maximise fitness
        objective_func=fitness_fn,
        solution_length=n_genes,        # one gene per weight/bias
        initial_bounds=tuple(init_bounds),  # weights initialised in [low, high]
        dtype=torch.float32,
        device=target_device,
        vectorized=True,                # fitness_fn takes/returns whole-population batches
    )

    operators = []
    if use_crossover:
        # eta (SBX's "distribution index"): higher = offspring cluster
        # closer to their parents, lower = offspring spread further apart.
        # tournament_size: how many individuals compete for each parent
        # slot; higher = stronger pressure toward already-fit individuals.
        operators.append(SimulatedBinaryCrossOver(problem, tournament_size=tournament_size, eta=eta))
    operators.append(GaussianMutation(problem, stdev=mut_stdev))

    algorithm = GeneticAlgorithm(
        problem,
        popsize=popsize,
        operators=operators,
        elitist=elitism,   # best individual always survives → fitness never drops (default on)
    )

    # -- Seed the initial population, if requested --
    # GeneticAlgorithm builds its starting population in its constructor
    # (accessible as .population immediately, before the first .step()), so
    # overwriting it here applies before any evolution happens.
    if seed_genome_path is not None:
        seed_genome = torch.tensor(np.load(seed_genome_path), dtype=torch.float32, device=target_device)
        if seed_genome.numel() != n_genes:
            raise ValueError(
                f"Seed genome at '{seed_genome_path}' has {seed_genome.numel()} values, but "
                f"the current --hidden/--activation architecture expects {n_genes}. Make sure "
                f"these match what the seed genome was evolved with."
            )
        values = algorithm.population.access_values(keep_evals=False)
        values[0] = seed_genome  # one exact, unperturbed copy
        noise = torch.randn((popsize - 1, n_genes), device=target_device) * seed_noise
        values[1:] = seed_genome.unsqueeze(0) + noise

    best_fit  = np.zeros(gens)
    avg_fit   = np.zeros(gens)
    worst_fit = np.zeros(gens)
    convergence_gen = None  # generation perfect fitness was first reached (if any)

    for gen in range(gens):
        algorithm.step()

        fitnesses = algorithm.population.access_evals()[:, 0]
        # Replace any NaN values that may arise from bad mutations
        fitnesses = torch.where(torch.isnan(fitnesses), torch.zeros_like(fitnesses), fitnesses)

        best_fit[gen]  = fitnesses.max().item()
        avg_fit[gen]   = fitnesses.mean().item()
        worst_fit[gen] = fitnesses.min().item()

        if verbose and (gen % 10 == 0 or gen == gens - 1):
            pct = (fitnesses >= 1.0).float().mean().item() * 100
            print(f"Gen {gen:>4d} | Best: {best_fit[gen]:.4f} | "
                  f"Mean: {avg_fit[gen]:.4f} | Perfect: {int(pct)}%")

        # Early stopping once perfect fitness is found. Record the generation
        # this happened at *before* backfilling best_fit with 1.0s below —
        # otherwise that information is unrecoverable from best_fit alone.
        if best_fit[gen] >= 1.0:
            convergence_gen = gen
            if verbose:
                print(f"\nConverged at generation {gen}!")
            best_fit[gen:]  = 1.0
            avg_fit[gen:]   = avg_fit[gen]
            worst_fit[gen:] = worst_fit[gen]
            break

    # Retrieve the best genome
    fitnesses = algorithm.population.access_evals()[:, 0]
    fitnesses = torch.where(torch.isnan(fitnesses), torch.zeros_like(fitnesses), fitnesses)
    best_idx    = fitnesses.argmax().item()
    best_genome = algorithm.population.access_values()[best_idx].clone()
    best_fitness = fitnesses[best_idx].item()

    return best_fit, avg_fit, worst_fit, best_genome, best_fitness, inputs, signs, convergence_gen



# ─────────────────────────────────────────────────────────────
#  6.  Main Entry Point
# ─────────────────────────────────────────────────────────────

def main():
    """Command-line entry point for neuroevolution experiments (XOR / random / convex).

    Parses CLI arguments, runs neuroevolution with the selected configuration,
    and optionally plots fitness curves and decision boundaries.
    """
    args = parse_args()

    # Determine which problem to use
    if args.convex is not None:
        print(f"Evolving neural network on convex problem: "
              f"{args.convex} points on circle (alternating labels), hidden={args.hidden}, "
              f"activation={args.activation}, popsize={args.popsize}, gens={args.gens}")
    elif args.random is not None:
        print(f"Evolving neural network on random problem: "
              f"{args.random} points, hidden={args.hidden}, "
              f"activation={args.activation}, popsize={args.popsize}, gens={args.gens}")
    else:
        print(f"Evolving {args.task.upper()} controller: hidden={args.hidden}, "
              f"activation={args.activation}, popsize={args.popsize}, gens={args.gens}")

    if args.seed_genome:
        print(f"Seeding initial population from: {args.seed_genome} (seed_noise={args.seed_noise})")

    best_fit, avg_fit, worst_fit, best_genome, best_fitness, inputs, signs, convergence_gen = run_neuroevolution(
        hidden=args.hidden,
        popsize=args.popsize,
        gens=args.gens,
        mut_stdev=args.mut_stdev,
        activation=args.activation,
        verbose=args.verbose,
        seed=args.seed,
        random_points=args.random,
        convex_points=args.convex,
        device=args.device,
        tournament_size=args.tournament_size,
        eta=args.eta,
        elitism=args.elitism,
        seed_genome_path=args.seed_genome,
        seed_noise=args.seed_noise,
        hidden_sizes=args.hidden_sizes,
        fitness_mode=args.fitness_mode,
        task=args.task,
        init_bounds=tuple(args.init_bounds),
        use_crossover=args.use_crossover,
    )

    print(f"\nBest fitness achieved: {best_fitness:.4f}")
    if convergence_gen is not None:
        print(f"Converged at generation: {convergence_gen}")
    else:
        print(f"Did not reach perfect fitness within {args.gens} generations")

    if args.output:
        np.save(args.output, best_genome.cpu().numpy())
        print(f"Best genome saved to: {args.output}")

    if args.fitness_output:
        np.savez(args.fitness_output, best=best_fit, avg=avg_fit, worst=worst_fit)
        print(f"Fitness-over-generations saved to: {args.fitness_output}")

    print_truth_table_custom(best_genome, hidden=args.hidden, activation=args.activation,
                             inputs=inputs, signs=signs, hidden_sizes=args.hidden_sizes)

    # Determine problem name for display
    if args.convex is not None:
        problem_name = f"Convex({args.convex})"
    elif args.random is not None:
        problem_name = f"Random({args.random})"
    else:
        problem_name = args.task.upper()

    if args.vizperf:
        plot_fitness(best_fit, avg_fit, worst_fit, problem_name=problem_name)

    if args.vizbound:
        plot_decision_boundary_custom(best_genome, args.hidden, args.activation,
                                      best_fitness, inputs, signs, problem_name=problem_name,
                                      hidden_sizes=args.hidden_sizes)


if __name__ == "__main__":
    main()
